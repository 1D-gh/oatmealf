//! Writes the game uniform buffer layouts that differ from the editor as the data file read by the engine loader
//! (RenderCore/Private/UniformBufferTranslationLoader.cpp). Format: docs/cooked-materials-shaders.md of the modkit workspace.
//!
//! usage: uniform_layouts <game-layouts.json> <editor-layouts.json> <out.txt>

use anyhow::{Context, Result, anyhow, bail};
use serde_json::Value;
use std::collections::HashMap;
use std::fmt::Write as _;

/// Member types that occupy one pointer-sized slot in the constant data (RenderCore ShaderParameterMetadata: IsShaderParameterTypeForUniformBufferLayout).
const RESOURCE_TYPES: &[&str] = &[
    "SAMPLER",
    "SRV",
    "TEXTURE",
    "UAV",
    "RDG_TEXTURE",
    "RDG_TEXTURE_SRV",
    "RDG_TEXTURE_UAV",
    "RDG_BUFFER_SRV",
    "RDG_BUFFER_UAV",
    "REFERENCED_STRUCT",
    "RDG_UNIFORM_BUFFER",
    "RENDER_TARGET_BINDING_SLOTS",
];

const CONSTANT_TYPES: &[&str] = &["FLOAT32", "INT32", "UINT32"];

/// Keys of the game's resourceTables and the letter the data file uses for them.
const LIST_KEYS: &[(&str, char)] = &[
    ("Resources", 'R'),
    ("GraphResources", 'G'),
    ("GraphTextures", 'T'),
    ("GraphBuffers", 'B'),
    ("GraphUniformBuffers", 'U'),
    ("UniformBuffers", 'N'),
];

const POINTER_SIZE: u64 = 8;
const ARRAY_ELEMENT_ALIGNMENT: u64 = 16;

struct Leaf {
    path: String,
    offset: u64,
    size: u64,
    ty: String,
}

fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().collect();
    if args.len() != 4 {
        bail!("usage: uniform_layouts <game-layouts.json> <editor-layouts.json> <out.txt>");
    }
    let game = read_json(&args[1])?;
    let editor = read_json(&args[2])?;

    let mut editor_hashes: HashMap<String, u32> = HashMap::new();
    for layout in array(&editor, "layouts")? {
        editor_hashes.insert(text(layout, "name")?.to_string(), parse_hash(text(layout, "rhiHash")?)?);
    }

    let mut definitions: HashMap<u64, &Value> = HashMap::new();
    for definition in array(&game, "definitions")? {
        definitions.insert(u64_of(definition, "id")?, definition);
    }

    let mut out = String::new();
    writeln!(out, "# Game uniform buffer layouts that differ from the editor (generated by uniform_layouts from oatmealf game-layouts.json)")?;
    let mut exported = 0usize;
    let mut skipped = Vec::new();
    for layout in array(&game, "layouts")? {
        let name = text(layout, "name")?;
        let game_hash = parse_hash(text(layout, "rhiHash")?)?;
        // Game-only layouts have no editor counterpart and are not translated.
        let Some(&editor_hash) = editor_hashes.get(name) else {
            continue;
        };
        if editor_hash == game_hash {
            continue;
        }
        match export_layout(&definitions, layout, editor_hash, game_hash) {
            Ok(block) => {
                out.push_str(&block);
                exported += 1;
            }
            Err(error) => skipped.push(format!("{name}: {error:#}")),
        }
    }
    std::fs::write(&args[3], out).with_context(|| format!("writing {}", args[3]))?;
    println!("exported {exported} layouts to {}", args[3]);
    for line in &skipped {
        println!("skipped {line}");
    }
    Ok(())
}

fn export_layout(definitions: &HashMap<u64, &Value>, layout: &Value, editor_hash: u32, game_hash: u32) -> Result<String> {
    let mut leaves = Vec::new();
    flatten(definitions, u64_of(layout, "rootDefinitionId")?, 0, "", &mut leaves)?;

    for leaf in &leaves {
        let known = RESOURCE_TYPES.contains(&leaf.ty.as_str()) || CONSTANT_TYPES.contains(&leaf.ty.as_str());
        if !known {
            bail!("member '{}' has unsupported type {}", leaf.path, leaf.ty);
        }
    }

    // Every resource leaf must be in the game's Resources table, and every table entry must be a resource leaf of the same type.
    let mut resources_by_offset: HashMap<u64, &Leaf> = HashMap::new();
    for leaf in leaves.iter().filter(|leaf| RESOURCE_TYPES.contains(&leaf.ty.as_str())) {
        if resources_by_offset.insert(leaf.offset, leaf).is_some() {
            bail!("two resources at offset {}", leaf.offset);
        }
    }
    let tables = &layout["resourceTables"];
    let mut lists: Vec<(char, Vec<&str>)> = Vec::new();
    for (key, letter) in LIST_KEYS {
        let entries: &[Value] = tables[*key].as_array().map(|entries| entries.as_slice()).unwrap_or(&[]);
        let mut paths = Vec::new();
        for entry in entries {
            let offset = u64_of(entry, "offset")?;
            let ty = text(entry, "type")?;
            let leaf = resources_by_offset
                .get(&offset)
                .ok_or_else(|| anyhow!("{key} entry at offset {offset} is not a resource member"))?;
            if leaf.ty != ty {
                bail!("{key} entry at offset {offset} is {ty}, flattening found {}", leaf.ty);
            }
            paths.push(leaf.path.as_str());
        }
        if *letter == 'R' && paths.len() != resources_by_offset.len() {
            bail!("Resources has {} entries, flattening found {}", paths.len(), resources_by_offset.len());
        }
        lists.push((*letter, paths));
    }

    // The RHI layout hash covers the layout name, which is the editor's FShaderParametersMetadata::LayoutName.
    let layout_name = text(layout, "layoutName")?;
    let mut block = String::new();
    writeln!(
        block,
        "layout {layout_name} editor=0x{editor_hash:08X} game=0x{game_hash:08X} size={} flags={} binding={} static={} rtoffset={}",
        u64_of(layout, "constantBufferSize")?,
        u64_of(layout, "flags")?,
        u64_of(layout, "bindingFlags")?,
        u64_of(layout, "staticSlot")?,
        u64_of(layout, "renderTargetsOffset")?,
    )?;
    for leaf in &leaves {
        let default = default_key(leaf);
        writeln!(block, "leaf {} {} {} {} {}", leaf.offset, leaf.ty, leaf.size, default, leaf.path)?;
    }
    for (letter, paths) in &lists {
        if paths.is_empty() {
            continue;
        }
        write!(block, "list {letter}")?;
        for path in paths {
            write!(block, " {path}")?;
        }
        writeln!(block)?;
    }
    writeln!(block, "end")?;
    Ok(block)
}

/// Default for a resource member that has no editor counterpart, chosen to match what the game's own code
/// stores in those members (SceneTextures.cpp, VolumeLighting.cpp, FogRendering.cpp, LightGridInjection.cpp in the game's engine source).
fn default_key(leaf: &Leaf) -> &'static str {
    let member = leaf.path.rsplit('.').next().unwrap_or(&leaf.path);
    match leaf.ty.as_str() {
        "TEXTURE" | "RDG_TEXTURE" => {
            if member.ends_with("FogInscatteringColorCubemap") {
                "black_cube"
            } else if member.ends_with("ASMIndirectionTexture") || member.ends_with("StaticShadowDepthTexture") {
                "white_texture"
            } else {
                "black_texture"
            }
        }
        "SRV" | "RDG_TEXTURE_SRV" | "RDG_BUFFER_SRV" => {
            if leaf.ty == "RDG_BUFFER_SRV" || member.ends_with("Buffer") || member.ends_with("Buffers") {
                "black_buffer_srv"
            } else {
                "black_srv"
            }
        }
        "SAMPLER" => "point_sampler",
        _ => "-",
    }
}

/// Flattens a definition with the rules of FShaderParametersMetadata::InitializeLayout: resources one pointer each
/// (one per array element), nested and included structs recursed (struct arrays step by the struct size), constants
/// with arrays stepping by 16 byte aligned elements.
fn flatten(definitions: &HashMap<u64, &Value>, definition_id: u64, base: u64, prefix: &str, out: &mut Vec<Leaf>) -> Result<()> {
    let definition = definitions
        .get(&definition_id)
        .ok_or_else(|| anyhow!("missing definition {definition_id}"))?;
    for member in array(definition, "members")? {
        let member_name = text(member, "name")?;
        let ty = text(member, "type")?;
        let offset = base + u64_of(member, "offset")?;
        let elements = u64_of(member, "elements")?;
        let is_array = elements > 0;
        let count = elements.max(1);
        let full = format!("{prefix}{member_name}");

        if ty == "INCLUDED_STRUCT" || ty == "NESTED_STRUCT" {
            let child_id = u64_of(member, "nestedDefinitionId")?;
            let child = definitions
                .get(&child_id)
                .ok_or_else(|| anyhow!("missing nested definition {child_id}"))?;
            let child_size = u64_of(child, "size")?;
            for element in 0..count {
                let child_prefix = if is_array { format!("{full}[{element}].") } else { format!("{full}.") };
                flatten(definitions, child_id, offset + element * child_size, &child_prefix, out)?;
            }
        } else if RESOURCE_TYPES.contains(&ty) {
            for element in 0..count {
                let path = if is_array { format!("{full}[{element}]") } else { full.clone() };
                out.push(Leaf { path, offset: offset + element * POINTER_SIZE, size: POINTER_SIZE, ty: ty.to_string() });
            }
        } else {
            let element_size = 4 * u64_of(member, "rows")? * u64_of(member, "columns")?;
            let size = if is_array { align(element_size, ARRAY_ELEMENT_ALIGNMENT) * elements } else { element_size };
            out.push(Leaf { path: full, offset, size, ty: ty.to_string() });
        }
    }
    Ok(())
}

fn align(value: u64, alignment: u64) -> u64 {
    value.div_ceil(alignment) * alignment
}

fn read_json(path: &str) -> Result<Value> {
    let content = std::fs::read_to_string(path).with_context(|| format!("reading {path}"))?;
    serde_json::from_str(&content).with_context(|| format!("parsing {path}"))
}

fn array<'a>(value: &'a Value, key: &str) -> Result<&'a Vec<Value>> {
    value[key].as_array().ok_or_else(|| anyhow!("missing array '{key}'"))
}

fn text<'a>(value: &'a Value, key: &str) -> Result<&'a str> {
    value[key].as_str().ok_or_else(|| anyhow!("missing string '{key}'"))
}

fn u64_of(value: &Value, key: &str) -> Result<u64> {
    value[key].as_u64().ok_or_else(|| anyhow!("missing number '{key}'"))
}

fn parse_hash(text: &str) -> Result<u32> {
    let digits = text.trim_start_matches("0x").trim_start_matches("0X");
    u32::from_str_radix(digits, 16).with_context(|| format!("bad hash '{text}'"))
}
